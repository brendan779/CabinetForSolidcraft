//! Reading cabinets back from a SolidCraft design (SC-3). Each cabinet's spec is stored on its
//! component under [`crate::METADATA_KEY`] when it is built.

use serde_json::Value;

use crate::{Client, METADATA_KEY, Result};

/// The names of every component in a `component.list` result, the design's root left out.
pub fn component_names(listing: &Value) -> Vec<String> {
    listing["components"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|c| !c["parent"].is_null())
        .filter_map(|c| c["name"].as_str().map(String::from))
        .collect()
}

/// The cabinet spec in a `component.metadata` result, if the component is one of ours.
pub fn spec_from_metadata(metadata: &Value) -> Option<Value> {
    metadata["metadata"]
        .get(METADATA_KEY)
        .filter(|v| v.is_object())
        .cloned()
}

/// The specs of every cabinet built into the open design, in component order.
pub fn cabinets_in_design(client: &mut Client) -> Result<Vec<Value>> {
    let mut specs = Vec::new();
    for name in component_names(&client.components()?) {
        let meta = client.execute(
            "component.metadata",
            serde_json::json!({ "component": name }),
        )?;
        specs.extend(spec_from_metadata(&meta));
    }
    Ok(specs)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn the_root_is_not_a_cabinet_candidate() {
        let listing = json!({ "components": [
            { "id": 0, "name": "Untitled", "parent": null },
            { "id": 1, "name": "B01", "parent": 0 },
            { "id": 4, "name": "Hinge", "parent": 1 },
        ] });
        assert_eq!(component_names(&listing), ["B01", "Hinge"]);
    }

    #[test]
    fn only_components_with_our_key_hold_a_cabinet() {
        let ours = json!({ "name": "B01", "metadata": {
            "description": "Cabinet generated by CabinetForSolidcraft",
            METADATA_KEY: { "id": "B01", "kind": "base" } } });
        let theirs = json!({ "name": "Other", "metadata": { "com.example.tool": { "id": 3 } } });
        assert_eq!(spec_from_metadata(&ours).unwrap()["id"], "B01");
        assert_eq!(spec_from_metadata(&theirs), None);
        assert_eq!(spec_from_metadata(&json!({ "metadata": {} })), None);
    }
}
