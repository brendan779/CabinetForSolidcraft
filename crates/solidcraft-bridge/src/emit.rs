//! Part lists → SolidCraft engine commands.

use cabinet_core::PartList;
use cabinet_core::geom::{Axis, Vec3};
use cabinet_core::part::{Operation, PartRole};
use serde_json::{Value, json};

/// How much of the machining to model.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Detail {
    /// Plain panels. Fast; for layout and presentation.
    Design,
    /// Panels with every bore, groove and biscuit slot cut. For checking and export.
    Manufacturing,
}

fn axis_name(a: Axis) -> &'static str {
    match a {
        Axis::X => "X",
        Axis::Y => "Y",
        Axis::Z => "Z",
    }
}

fn arr(v: Vec3) -> Value {
    json!([round(v.x), round(v.y), round(v.z)])
}

/// Keeps commands readable and stable across runs: 1/1000 mm is far below machining tolerance.
fn round(v: f64) -> f64 {
    (v * 1000.0).round() / 1000.0
}

fn colour(role: PartRole) -> &'static str {
    match role {
        PartRole::Door | PartRole::DrawerFront | PartRole::Plinth => "#c9a77c",
        PartRole::Back => "#b9b4aa",
        _ => "#ece9e2",
    }
}

/// The commands that build `list` inside a new component named after the cabinet, then return to
/// the root component. `spec` is stored on the component so the cabinet can be edited later.
pub fn emit_cabinet(list: &PartList, detail: Detail, spec: Option<&Value>) -> Vec<Value> {
    let mut cmds = vec![json!({
        "command": "component.create",
        "params": { "name": list.cabinet, "activate": true }
    })];
    for p in &list.parts {
        cmds.push(json!({
            "command": "solid.box",
            "params": {
                "length": round(p.bounds.size.x),
                "width": round(p.bounds.size.y),
                "height": round(p.bounds.size.z),
                "corner": arr(p.bounds.min),
                "operation": "new",
                "body_name": p.name,
                "name": p.name,
            }
        }));
    }
    if detail == Detail::Manufacturing {
        for op in &list.operations {
            cmds.push(operation(op));
        }
    }
    // One appearance command per colour keeps the batch short.
    let mut by_colour: Vec<(&str, Vec<&str>)> = Vec::new();
    for p in &list.parts {
        let c = colour(p.role);
        match by_colour.iter_mut().find(|(k, _)| *k == c) {
            Some((_, v)) => v.push(&p.name),
            None => by_colour.push((c, vec![&p.name])),
        }
    }
    for (c, bodies) in by_colour {
        cmds.push(
            json!({ "command": "appearance.assign", "params": { "bodies": bodies, "color": c } }),
        );
    }
    if let Some(spec) = spec {
        cmds.push(json!({
            "command": "component.metadata.set",
            "params": {
                "component": list.cabinet,
                "description": "Cabinet generated by CabinetForSolidcraft",
                "values": { crate::METADATA_KEY: spec }
            }
        }));
    }
    cmds.push(json!({ "command": "component.activate", "params": { "component": "root" } }));
    cmds
}

fn operation(op: &Operation) -> Value {
    match op {
        Operation::Bore {
            part,
            at,
            direction,
            diameter,
            depth,
            ..
        } => {
            // A cylinder grows from its base along the positive axis.
            let base = if direction.positive {
                *at
            } else {
                at.with(direction.axis, at.get(direction.axis) - depth)
            };
            json!({
                "command": "solid.cylinder",
                "params": {
                    "diameter": round(*diameter),
                    "height": round(*depth),
                    "base": arr(base),
                    "axis": axis_name(direction.axis),
                    "operation": "cut",
                    "targets": [part],
                }
            })
        }
        Operation::BiscuitSlot { parts, bounds, .. } => {
            cut_box(bounds.min, bounds.size, parts.as_slice())
        }
        Operation::Groove { part, bounds } => {
            cut_box(bounds.min, bounds.size, std::slice::from_ref(part))
        }
    }
}

fn cut_box(min: Vec3, size: Vec3, targets: &[String]) -> Value {
    json!({
        "command": "solid.box",
        "params": {
            "length": round(size.x),
            "width": round(size.y),
            "height": round(size.z),
            "corner": arr(min),
            "operation": "cut",
            "targets": targets,
        }
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use cabinet_core::{Cabinet, CabinetKind, build_cabinet};

    #[test]
    fn design_detail_makes_one_box_per_part() {
        let list = build_cabinet(&Cabinet::new("B01", CabinetKind::Base)).unwrap();
        let cmds = emit_cabinet(&list, Detail::Design, None);
        let boxes = cmds.iter().filter(|c| c["command"] == "solid.box").count();
        assert_eq!(boxes, list.parts.len());
        assert_eq!(cmds.first().unwrap()["command"], "component.create");
        assert_eq!(cmds.last().unwrap()["command"], "component.activate");
    }

    #[test]
    fn manufacturing_detail_cuts_every_operation() {
        let list = build_cabinet(&Cabinet::new("B01", CabinetKind::Base)).unwrap();
        let design = emit_cabinet(&list, Detail::Design, None).len();
        let mfg = emit_cabinet(&list, Detail::Manufacturing, None).len();
        assert_eq!(mfg - design, list.operations.len());
    }

    #[test]
    fn a_bore_into_negative_direction_starts_at_its_bottom() {
        use cabinet_core::part::{BorePurpose, Dir};
        let op = Operation::Bore {
            part: "P".into(),
            at: Vec3::new(10.0, 0.0, 5.0),
            direction: Dir::new(Axis::Y, false),
            diameter: 35.0,
            depth: 13.0,
            purpose: BorePurpose::HingeCup,
        };
        let v = operation(&op);
        assert_eq!(v["params"]["base"], json!([10.0, -13.0, 5.0]));
        assert_eq!(v["params"]["axis"], "Y");
    }
}
